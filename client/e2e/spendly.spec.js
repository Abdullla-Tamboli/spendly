import { test, expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';

test('all pages render real MongoDB data at mobile, tablet and desktop widths', async ({ page }) => {
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.goto('/login');
  await page.getByLabel('Email', { exact: true }).fill('demo@spendly.dev');
  await page.getByLabel('Password', { exact: true }).fill(process.env.SEED_PASSWORD || 'SpendlyReview2026!');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Welcome back, Alex.' })).toBeVisible();
  await mkdir('../docs/screenshots', { recursive: true });
  for (const width of [1280, 768, 360]) {
    await page.setViewportSize({ width, height: 900 });
    for (const [route, title] of [['/', 'Welcome back, Alex.'], ['/transactions', 'Transactions'], ['/analytics', 'Analytics'], ['/accounts', 'Accounts & wallets'], ['/budgets', 'Budgets'], ['/recurring', 'Recurring transactions'], ['/goals', 'Savings goals'], ['/settings', 'Settings']]) {
      await page.goto(route);
      await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible();
      await expect(page.getByRole('status', { name: 'Loading data', exact: true })).toHaveCount(0);
      await expect(page.getByRole('button', { name: 'Retry', exact: true })).toHaveCount(0);
      const size = await page.evaluate(() => ({ scroll: document.documentElement.scrollWidth, width: window.innerWidth }));
      expect(size.scroll, route + ' at width ' + width).toBeLessThanOrEqual(size.width);
      if (width === 1280 || (width === 360 && ['/', '/transactions'].includes(route))) await page.screenshot({ path: '../docs/screenshots/' + (route === '/' ? 'dashboard' : route.slice(1)) + '-' + width + '.png', fullPage: true });
    }
  }
  expect(errors).toEqual([]);
});

test('register, transaction CRUD, filters, CSV, budgets, goals, recurring, settings and logout', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 900 });
  const email = 'review-' + Date.now() + '@spendly.dev';
  await page.goto('/register');
  await page.getByLabel('Name', { exact: true }).fill('Review User');
  await page.getByLabel('Email', { exact: true }).fill(email);
  await page.getByLabel('Password', { exact: true }).fill('ReviewPassword2026!');
  await page.getByRole('button', { name: 'Create account', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Welcome back, Review.' })).toBeVisible();
  await page.getByRole('button', { name: 'Add transaction', exact: true }).click();
  await page.getByRole('button', { name: 'Income', exact: true }).click();
  await page.getByLabel('Amount', { exact: true }).fill('1000');
  await page.getByLabel('Category', { exact: true }).selectOption('Salary');
  await page.getByLabel('Note (optional)').fill('QA salary');
  await page.getByRole('dialog').getByRole('button', { name: 'Add transaction', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.getByText('$1,000.00', { exact: true }).first()).toBeVisible();
  await page.goto('/transactions');
  await page.getByRole('button', { name: 'Add transaction', exact: true }).click();
  await page.getByLabel('Amount', { exact: true }).fill('25.5');
  await page.getByLabel('Category', { exact: true }).selectOption('Food');
  await page.getByLabel('Note (optional)').fill('QA lunch');
  await page.getByLabel('Make this recurring').check();
  await page.getByRole('dialog').getByRole('button', { name: 'Add transaction', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.getByRole('cell', { name: 'Food QA lunch' })).toBeVisible();
  await page.getByRole('button', { name: 'Edit Food transaction' }).first().click();
  await page.getByLabel('Amount', { exact: true }).fill('30');
  await page.getByRole('button', { name: 'Save changes', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByLabel('Transaction type filter').selectOption('expense');
  await expect(page.getByRole('cell', { name: '-$30.00', exact: true })).toBeVisible();
  await expect(page.getByRole('cell', { name: 'Salary QA salary' })).toHaveCount(0);
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export CSV' }).click();
  const exported = await download;
  expect(exported.suggestedFilename()).toBe('spendly-transactions.csv');
  const stream = await exported.createReadStream();
  let csv = ''; for await (const chunk of stream) csv += chunk.toString();
  expect(csv).toContain('Date,Type,Category,Account,Amount,Note');
  expect(csv).toContain('Expense,Food,Cash,30,QA lunch');
  expect(csv).not.toContain('QA salary');
  await page.reload();
  await expect(page.getByLabel('Transaction type filter')).toHaveValue('expense');
  await page.goto('/budgets');
  await page.getByRole('button', { name: 'Set budget', exact: true }).click();
  await page.getByLabel('Overall monthly budget').fill('40');
  await page.getByRole('button', { name: 'Add category limit' }).click();
  await page.getByLabel('Category', { exact: true }).selectOption('Food');
  await page.getByLabel('Category limit').fill('40');
  await page.getByRole('button', { name: 'Save budget' }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.getByText('75% used', { exact: true }).first()).toBeVisible();
  await page.goto('/goals');
  await page.getByRole('button', { name: 'Create goal', exact: true }).click();
  await page.getByLabel('Goal name').fill('QA laptop');
  await page.getByLabel('Target amount').fill('500');
  await page.getByRole('dialog').getByRole('button', { name: 'Create goal', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'QA laptop', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Add funds', exact: true }).click();
  await page.getByLabel('Amount to add').fill('100');
  await page.getByRole('dialog').getByRole('button', { name: 'Add funds', exact: true }).click();
  await expect(page.getByText('20%', { exact: true })).toBeVisible();
  await page.goto('/recurring');
  await expect(page.getByRole('heading', { name: 'QA lunch', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Pause Food' }).click();
  await expect(page.getByText('Paused / ended')).toBeVisible();
  await page.getByRole('button', { name: 'Resume Food' }).click();
  await expect(page.getByText('Active', { exact: true })).toBeVisible();
  await page.goto('/settings');
  await page.getByLabel('Display currency').selectOption('INR');
  await page.getByRole('button', { name: 'Save profile' }).click();
  await expect(page.getByRole('status').filter({ hasText: 'Profile updated' })).toBeVisible();
  await page.reload();
  await expect(page.getByLabel('Display currency')).toHaveValue('INR');
  await page.goto('/transactions');
  await page.getByRole('button', { name: 'Delete Food transaction' }).first().click();
  await page.getByRole('dialog').getByRole('button', { name: 'Delete', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Delete Food transaction' })).toHaveCount(0);
  await page.goto('/settings');
  await page.getByRole('button', { name: 'Sign out', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Sign in', exact: true })).toBeVisible();
  await page.getByLabel('Email', { exact: true }).fill(email);
  await page.getByLabel('Password', { exact: true }).fill('ReviewPassword2026!');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Welcome back, Review.' })).toBeVisible();
});
